/**
 * Public Chat Types
 */

export interface PublicConversation {
  id: string; // "userId1_userId2" (sorted alphabetically)
  participants: string[]; // [userId1, userId2]
  participantsData: {
    [userId: string]: {
      name: string;
      displayName: string;
      avatar: string;
      email: string;
    };
  };
  lastMessage: {
    text: string;
    senderId: string;
    timestamp: string;
    mediaUrl?: string;
    mediaType?: 'image' | 'video' | 'document';
    mediaName?: string;
  } | null;
  unreadCount: {
    [userId: string]: number; // userId: number of unread messages
  };
  createdAt: string;
  updatedAt: string;
}

export interface PublicChatMessage {
  id: string; // auto-generated by Firestore
  conversationId: string; // reference to parent conversation
  senderId: string;
  receiverId: string;
  text: string;
  mediaUrl?: string; // Firebase Storage URL
  mediaType?: 'image' | 'video' | 'document'; // image/video/pdf etc
  mediaSize?: number; // in bytes
  mediaName?: string; // original filename
  timestamp: string;
  read: boolean; // has receiver seen it?
  readAt?: string; // when was it read?
}

export interface ChatNotification {
  id: string;
  conversationId: string;
  senderId: string;
  senderName: string;
  senderAvatar: string;
  message: string;
  timestamp: string;
  read: boolean;
}
